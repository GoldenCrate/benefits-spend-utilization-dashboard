"""
data_gen.py — Synthetic ICHRA health-benefits spend & utilization generator.

================================ IMPORTANT ================================
ALL DATA PRODUCED BY THIS SCRIPT IS 100% SYNTHETIC AND FICTIONAL.
It is generated by a random-number generator from a fixed seed. It does
NOT describe any real person, real employer, real health plan, real insurer,
or any real health or claims record. Employer names, plans, allowances, and
premiums are invented labels and numbers. This project exists only to
demonstrate data-modeling, analytics, and dashboarding skills. Do NOT
interpret any number here as a real-world fact and do NOT treat any field as
protected health information — none of it is real.
==========================================================================

Domain context (synthetic): ICHRA — an Individual Coverage Health
Reimbursement Arrangement — is a benefit where an employer gives each
employee a fixed monthly ALLOWANCE to buy their own individual health plan.
The employee browses plans, selects one, and activates coverage; the employer
reimburses premiums up to the allowance. Unused allowance is generally
forfeited ("use it or lose it"), so ALLOWANCE UTILIZATION (dollars used /
dollars offered) is a core business metric.

Running this file writes three CSVs into ./data, shaped like a small
dbt-modeled warehouse:
  - dim_employers.csv : lookup table of employers (size, industry)
  - dim_members.csv   : one row per enrolled member (allowance, funnel stage,
                        selected plan, premium, status)
  - fct_monthly_spend.csv : one row per (active member, month): allowance
                        offered and allowance actually used that month

These are clean by construction; analytics.py still runs a staging-style
cleaning pass so the pattern is demonstrated and unit-tested.
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd

SEED = 20260408
N_EMPLOYERS = 24
N_MEMBERS = 4200
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")

# A fixed "as-of" reporting month so utilization snapshots and cohort
# follow-up windows are deterministic regardless of when this is run.
AS_OF_MONTH = "2025-09"
# Members enroll across these monthly cohorts (growing book of business).
FIRST_COHORT = "2025-01"

EMPLOYER_SIZES = ["Small", "Mid-market", "Large"]
INDUSTRIES = [
    "Retail",
    "Professional Services",
    "Construction",
    "Healthcare",
    "Hospitality",
    "Technology",
    "Manufacturing",
]

FUNNEL_STAGES = ["Enrolled", "Browsed", "Selected Plan", "Active"]
METAL_TIERS = ["Bronze", "Silver", "Gold", "Platinum"]

# Base monthly allowance (employer contribution, USD) by employer size.
ALLOWANCE_BASE = {"Small": 450.0, "Mid-market": 575.0, "Large": 700.0}
# Base monthly premium (USD) of the selected individual plan by metal tier.
PREMIUM_BASE = {"Bronze": 380.0, "Silver": 480.0, "Gold": 600.0, "Platinum": 760.0}


# --------------------------------------------------------------------------- #
# Month helpers ("YYYY-MM" <-> integer month index)
# --------------------------------------------------------------------------- #
def _month_index(ym: str) -> int:
    y, m = ym.split("-")
    return int(y) * 12 + (int(m) - 1)


def _index_to_month(idx: int) -> str:
    y, m = divmod(idx, 12)
    return f"{y:04d}-{m + 1:02d}"


def _month_range(start: str, end: str) -> list[str]:
    a, b = _month_index(start), _month_index(end)
    return [_index_to_month(i) for i in range(a, b + 1)]


COHORTS = _month_range(FIRST_COHORT, AS_OF_MONTH)[:-1]  # Jan..Aug 2025


# --------------------------------------------------------------------------- #
# Dimension: employers
# --------------------------------------------------------------------------- #
def _make_employers(rng: np.random.Generator) -> pd.DataFrame:
    # Realistic mix: lots of small employers, fewer large ones.
    sizes = rng.choice(EMPLOYER_SIZES, size=N_EMPLOYERS, p=[0.5, 0.33, 0.17])
    rows = []
    for i in range(N_EMPLOYERS):
        rows.append(
            {
                "employer_id": 2000 + i,
                "employer_name": f"Employer {i + 1:02d}",
                "employer_size": str(sizes[i]),
                "industry": str(rng.choice(INDUSTRIES)),
            }
        )
    return pd.DataFrame(rows)


# --------------------------------------------------------------------------- #
# Dimension: members (enrollment + funnel + selected plan)
# --------------------------------------------------------------------------- #
def _furthest_stage(rng: np.random.Generator) -> str:
    """Walk the plan-selection funnel; return the furthest stage reached."""
    # Conversion probabilities between consecutive stages (synthetic).
    if rng.random() >= 0.90:  # Enrolled -> Browsed
        return "Enrolled"
    if rng.random() >= 0.82:  # Browsed -> Selected Plan
        return "Browsed"
    if rng.random() >= 0.91:  # Selected Plan -> Active
        return "Selected Plan"
    return "Active"


def generate_members(
    rng: np.random.Generator, employers: pd.DataFrame
) -> pd.DataFrame:
    emp_ids = employers["employer_id"].to_numpy()
    emp_size = dict(zip(employers["employer_id"], employers["employer_size"]))

    # Growing enrollment: later cohorts are larger (book of business scaling).
    cohort_weights = np.linspace(1.0, 2.1, len(COHORTS))
    cohort_weights = cohort_weights / cohort_weights.sum()

    rows = []
    for i in range(N_MEMBERS):
        member_id = 500000 + i
        employer_id = int(rng.choice(emp_ids))
        size = emp_size[employer_id]
        cohort = str(rng.choice(COHORTS, p=cohort_weights))

        allowance = float(
            np.clip(rng.normal(ALLOWANCE_BASE[size], 90), 150, 1500)
        )
        allowance = round(allowance, 2)

        stage = _furthest_stage(rng)

        # Metal tier + premium only exist once a plan has been selected.
        if stage in ("Selected Plan", "Active"):
            tier = str(rng.choice(METAL_TIERS, p=[0.30, 0.40, 0.22, 0.08]))
            premium = float(
                np.clip(rng.normal(PREMIUM_BASE[tier], 110), 120, 2200)
            )
            premium = round(premium, 2)
        else:
            tier = ""
            premium = np.nan

        rows.append(
            {
                "member_id": member_id,
                "employer_id": employer_id,
                "enrollment_month": cohort,
                "monthly_allowance": allowance,
                "funnel_stage": stage,
                "metal_tier": tier,
                "monthly_premium": premium,
                "status": "Active" if stage == "Active" else "Inactive",
            }
        )

    return pd.DataFrame(rows)


# --------------------------------------------------------------------------- #
# Fact: monthly allowance spend for active members
# --------------------------------------------------------------------------- #
def _ramp_factor(tenure_months: int) -> float:
    """Utilization ramps up in the first few months after enrollment.

    Members finalize plans and reimbursements settle over the first quarter,
    so early-tenure months show lower utilization than steady state.
    """
    return {0: 0.55, 1: 0.80, 2: 0.93}.get(tenure_months, 1.0)


def generate_monthly_spend(
    rng: np.random.Generator, members: pd.DataFrame
) -> pd.DataFrame:
    as_of = _month_index(AS_OF_MONTH)
    active = members[members["status"] == "Active"]

    rows = []
    for m in active.itertuples(index=False):
        allowance = float(m.monthly_allowance)
        premium = float(m.monthly_premium)
        # Steady-state dollars used = premium reimbursed, capped at allowance.
        steady_used = min(premium, allowance)

        enroll_idx = _month_index(m.enrollment_month)
        for month_idx in range(enroll_idx, as_of + 1):
            tenure = month_idx - enroll_idx
            noise = rng.normal(1.0, 0.03)
            used = steady_used * _ramp_factor(tenure) * noise
            used = float(np.clip(used, 0.0, allowance))
            rows.append(
                {
                    "member_id": m.member_id,
                    "month": _index_to_month(month_idx),
                    "monthly_allowance": round(allowance, 2),
                    "allowance_used": round(used, 2),
                }
            )

    return pd.DataFrame(rows)


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
def main() -> None:
    os.makedirs(DATA_DIR, exist_ok=True)
    rng = np.random.default_rng(SEED)

    employers = _make_employers(rng)
    members = generate_members(rng, employers)
    monthly = generate_monthly_spend(rng, members)

    employers.to_csv(os.path.join(DATA_DIR, "dim_employers.csv"), index=False)
    members.to_csv(os.path.join(DATA_DIR, "dim_members.csv"), index=False)
    monthly.to_csv(
        os.path.join(DATA_DIR, "fct_monthly_spend.csv"), index=False
    )

    print("Synthetic data written to:", DATA_DIR)
    print(f"  dim_employers.csv     : {len(employers):,} rows")
    print(f"  dim_members.csv       : {len(members):,} rows")
    print(f"  fct_monthly_spend.csv : {len(monthly):,} rows")
    print(f"  cohorts               : {COHORTS[0]} .. {COHORTS[-1]}")
    print(f"  as-of month           : {AS_OF_MONTH}")
    print("NOTE: All data is synthetic. Not real people, employers, or claims.")


if __name__ == "__main__":
    main()
